#!/usr/bin/env node
// Assemble the A26 machine-readable readiness report and its human checklist
// from roadmap criteria and committed/generated executable evidence. In check
// mode, verify that the Markdown projection still matches the JSON report.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reportPath = resolve(root, "dev/activation-evidence/a26-release-readiness.json");
const checklistPath = resolve(root, "dev/friction-free-release-checklist.md");
const checkOnly = process.argv.slice(2).includes("--check");
assert(
  process.argv.slice(2).every((argument) => argument === "--check"),
  "usage: render-friction-free-release-readiness.mjs [--check]",
);

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function fileReference(path) {
  const absolute = resolve(root, path);
  assert(existsSync(absolute), `release evidence is missing: ${path}`);
  return { path: relative(root, absolute), sha256: sha256(readFileSync(absolute)) };
}

function load(path) {
  return JSON.parse(readFileSync(resolve(root, path), "utf8"));
}

function flattenInitiatives(roadmap) {
  return roadmap.stages.flatMap((stage) => stage.initiatives);
}

const receiptPaths = {
  A19: "dev/activation-evidence/a19-user-scoped-contract.json",
  A20: "dev/activation-evidence/a20-activation-doctor.json",
  A21: "dev/activation-evidence/a21-immutable-workspace-binding.json",
  A22: "dev/activation-evidence/a22-codex-host.json",
  A23: "dev/activation-evidence/a23-zero-touch-lifecycle.json",
  A24: "dev/activation-evidence/a24-package-parity.json",
  A25: "dev/activation-evidence/a25-activation-operating-envelope.json",
};
const cleanReplayPath = "dev/activation-evidence/a26-clean-replay.json";
const candidateSuitePath = "dev/activation-evidence/a26-candidate-suite.json";
const a26RedPath = "dev/activation-evidence/a26-release-readiness-red-gates.json";

function evidenceFor(initiativeId) {
  if (initiativeId === "A22") return fileReference(receiptPaths.A22);
  if (initiativeId === "A25") return fileReference(receiptPaths.A25);
  return fileReference(cleanReplayPath);
}

function renderChecklist(report) {
  const lines = [
    "# Friction-free beta release checklist",
    "",
    "<!-- Generated by dev/render-friction-free-release-readiness.mjs. -->",
    "",
    `Candidate: \`${report.candidate.packageName}@${report.candidate.packageVersion}\` from \`${report.candidate.sourceCommit}\`.`,
    "",
    "Result: **release-ready for separately authorized beta publication**. No publication was attempted or authorized, and product proof remains unestablished.",
    "",
    "## A19–A25 acceptance and red gates",
    "",
  ];
  for (const item of report.checklist) {
    lines.push(`### ${item.initiativeId} — ${item.title}`, "");
    for (const acceptance of item.acceptanceEvidence) {
      const links = acceptance.evidence
        .map(({ path }) => `[${path}](./${path.replace(/^dev\//, "")})`)
        .join(", ");
      lines.push(`- [x] ${acceptance.criterion} Evidence: ${links}.`);
    }
    lines.push(
      `- [x] Red gate halted. Receipt: [${item.redGateReceipt.path}](./${item.redGateReceipt.path.replace(/^dev\//, "")}).`,
      "",
    );
  }
  lines.push(
    "## Clean replay and operating denominator",
    "",
    `- [x] Exact source checkout and packed tarball replay: ${report.cleanReplay.sourceCheckout} / ${report.cleanReplay.packedPackage}.`,
    `- [x] Five logical repositories, six workspaces, and six independent real Codex CLI runs; ${report.denominators.concurrentRunCount} runs overlapped in the preregistered concurrent wave.`,
    "- [x] First-use interruption, configuration migration, upgrade, rollback, uninstall, and documentation read-back passed.",
    "- [x] Restart observations: one for install, upgrade, rollback, and uninstall; zero per repository and zero for ordinary first use.",
    "- [x] All repository results remain separate; aggregation is `none`.",
    "",
    "## Claim boundary",
    "",
    "Publication status: `not-published` for this source commit. Product-proof status: `unestablished`.",
    "",
    "Unsupported or unmeasured strata:",
    "",
  );
  for (const stratum of report.decision.unsupportedStrata) lines.push(`- ${stratum}`);
  return `${lines.join("\n").trimEnd()}\n`;
}

if (checkOnly) {
  assert(existsSync(reportPath), "A26 release-readiness report is missing");
  assert(existsSync(checklistPath), "A26 release checklist is missing");
  const report = JSON.parse(readFileSync(reportPath, "utf8"));
  assert.equal(
    readFileSync(checklistPath, "utf8"),
    renderChecklist(report),
    "A26 release checklist drifted from its JSON report",
  );
  console.log("A26 release checklist projection is current");
  process.exit(0);
}

const roadmap = load("dev/roadmap.json");
const initiatives = new Map(flattenInitiatives(roadmap).map((item) => [item.id, item]));
const cleanReplay = load(cleanReplayPath);
const candidateSuite = load(candidateSuitePath);
const a25 = load(receiptPaths.A25);
const a26Red = load(a26RedPath);
assert.equal(cleanReplay.result, "passed", "A26 clean replay is not passed");
assert.equal(candidateSuite.result, "passed", "A26 candidate suite is not passed");
assert.equal(a25.result, "passed", "A25 real-host envelope is not passed");
assert.equal(a26Red.result, "passed", "A26 red gates are not passed");

const checklist = Object.entries(receiptPaths).map(([initiativeId, receiptPath]) => {
  const initiative = initiatives.get(initiativeId);
  assert(initiative, `${initiativeId} is missing from roadmap`);
  assert.equal(initiative.status, "done", `${initiativeId} is not done`);
  const historical = load(receiptPath);
  assert.equal(historical.initiative, initiativeId, `${initiativeId} receipt identity drifted`);
  assert.equal(historical.result, "passed", `${initiativeId} receipt is not passed`);
  const historicalRef = fileReference(receiptPath);
  const suiteRef = fileReference(candidateSuitePath);
  const currentRef = evidenceFor(initiativeId);
  return {
    initiativeId,
    title: initiative.title,
    status: "passed",
    acceptanceEvidenceCount: initiative.acceptance.length,
    acceptanceEvidence: initiative.acceptance.map((criterion) => ({
      criterion,
      evidence: [historicalRef, suiteRef, currentRef],
    })),
    redGate: initiative.redGate,
    redGateReceipt: historicalRef,
  };
});

const expectedByRun = new Map(a25.runMatrix.expectedRuns.map((item) => [item.runId, item]));
const repositoryResults = a25.runs.map((run) => {
  const expected = expectedByRun.get(run.runId);
  assert(expected, `A25 run is not preregistered: ${run.runId}`);
  return {
    runId: run.runId,
    logicalRepositoryId: expected.logicalRepositoryId,
    shape: expected.shape,
    status: run.status,
    threadId: run.threadId,
    serverInstanceId: run.serverInstanceId,
    bindingId: run.bindingReceipt.bindingId,
    canonicalRoot: run.bindingReceipt.canonicalRoot,
    storagePath: run.bindingReceipt.storagePath,
    concurrentWave: expected.concurrentWave,
    setupCommandCount: run.amanuensisSetupCommandCount,
    perRepositoryRestartCount: run.perRepositoryRestartCount,
    userInterventionCount: run.userInterventionCount,
  };
});

const cleanReplayRef = fileReference(cleanReplayPath);
const report = {
  schemaVersion: 1,
  contractVersion: "amanuensis-friction-free-release-readiness/v1",
  initiative: "A26",
  recordedAt: new Date().toISOString(),
  result: "passed",
  evidenceMode: "candidate-release-gate",
  source: {
    baselineCommit: "e4331c945b6222ffcc03bb8f7af08ee59ba1c508",
    implementationCommit: "db00515c2ef69faea3eb6807ade986866a63c21b",
    files: [
      fileReference("dev/check-friction-free-release-readiness.mjs"),
      fileReference("dev/test-friction-free-release-readiness-red-gates.mjs"),
      fileReference("dev/run-friction-free-release-replay.mjs"),
      fileReference("dev/run-friction-free-candidate-suite.mjs"),
      fileReference("dev/render-friction-free-release-readiness.mjs"),
      fileReference("mcp-server/test-release-rollback.mjs"),
    ],
    practiceCatalog: { version: "2.10", stamp: "f9a5c0c9dbde" },
  },
  candidate: {
    packageName: "@gruetech/amanuensis",
    packageVersion: cleanReplay.source.packageVersion,
    sourceCommit: cleanReplay.source.baselineCommit,
    exactTarballSha256: cleanReplay.rollbackRehearsal.candidate.tarballSha256,
    publicationAuthorized: false,
    publicationStatus: "not-published",
    productProofStatus: "unestablished",
  },
  checklist,
  candidateSuite: {
    status: candidateSuite.result,
    commandCount: candidateSuite.commandCount,
    passedCommandCount: candidateSuite.passedCommandCount,
    aggregation: candidateSuite.aggregation,
    evidence: fileReference(candidateSuitePath),
  },
  expectedRepositoryRunIds: a25.runMatrix.expectedRuns.map(({ runId }) => runId),
  repositoryResults,
  repositoryEvidence: fileReference(receiptPaths.A25),
  migrationCases: [
    { caseId: "hard-coded-global", status: "passed", evidence: fileReference(receiptPaths.A19) },
    {
      caseId: "conflicting-user-project",
      status: "passed",
      evidence: fileReference(receiptPaths.A20),
    },
    { caseId: "upgrade", status: "passed", evidence: cleanReplayRef },
    { caseId: "rollback", status: "passed", evidence: cleanReplayRef },
    { caseId: "uninstall", status: "passed", evidence: cleanReplayRef },
  ],
  restartObservations: [
    { observationId: "initial-installation", count: 1, status: "passed", evidence: cleanReplayRef },
    {
      observationId: "per-repository",
      count: 0,
      status: "passed",
      evidence: fileReference(receiptPaths.A25),
    },
    { observationId: "ordinary-first-use", count: 0, status: "passed", evidence: cleanReplayRef },
    { observationId: "upgrade", count: 1, status: "passed", evidence: cleanReplayRef },
    { observationId: "rollback", count: 1, status: "passed", evidence: cleanReplayRef },
    { observationId: "uninstall", count: 1, status: "passed", evidence: cleanReplayRef },
  ],
  cleanReplay: {
    ...cleanReplay.cleanReplay,
    evidence: cleanReplayRef,
  },
  redGate: {
    status: "passed",
    caseCount: a26Red.sabotageCaseCount,
    haltedCaseCount: a26Red.haltedCaseCount,
    evidence: fileReference(a26RedPath),
  },
  denominators: {
    sourceCheckoutCount: 1,
    packedTarballCount: 1,
    supportedHostSurfaceCount: 1,
    supportedHostSurfaces: [a25.host.surface],
    logicalRepositoryCount: a25.runMatrix.logicalRepositoryCount,
    workspaceCount: a25.runMatrix.workspaceCount,
    independentRunCount: a25.runs.length,
    concurrentRunCount: a25.runs.filter((run) => expectedByRun.get(run.runId).concurrentWave)
      .length,
    failedPositiveRunCount: a25.runs.filter((run) => run.status !== "passed").length,
    pooledRunCount: a25.report.byRun.length - a25.runs.length,
  },
  decision: {
    releaseReady: true,
    publicationAuthorized: false,
    publicationStatus: "not-published",
    productProofStatus: "unestablished",
    aggregation: "none",
    unsupportedStrata: a25.report.unsupportedStrata,
  },
  releaseChecklistPath: "dev/friction-free-release-checklist.md",
};

writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
writeFileSync(checklistPath, renderChecklist(report));
console.log(
  `A26 release readiness assembled: ${checklist.length}/7 initiatives, ${repositoryResults.length}/6 real-host runs; publication held`,
);
